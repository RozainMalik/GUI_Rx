"""LEADERBOARD.md from the registry. Generated; never hand-edit the output."""
from __future__ import annotations

from pathlib import Path

from benchev.config import BENCH_ORDER, all_benches, load_bench
from benchev.registry import load

RANK = {"harness": 0, "imported": 1, "paper": 2}
ORDER = BENCH_ORDER


def _mark(r):
    if r.provenance == "paper":
        return "ᵖ"
    if r.provenance == "imported":
        return "ⁱ✓" if r.parity == "verified" else "ⁱ"
    return ""


def _val(r):
    m = r.metrics
    return m.get("acc", m.get("TCA (%)"))


def _canonical():
    return {b: load_bench(b).canonical for b in all_benches()}


def build(rows) -> str:
    canon = _canonical()
    main, other = [], []
    for r in rows:
        ok = r.status == "complete" and (r.protocol_id == canon.get(r.bench, f"{r.bench}@v1")
                                         or (r.provenance == "paper" and r.protocol_id == f"{r.bench}@paper"))
        (main if ok else other).append(r)
    best = {}
    for r in main:
        k = (r.model_id, r.bench, r.mode, r.split)
        if k not in best or RANK[r.provenance] < RANK[best[k].provenance]:
            best[k] = r
    models = sorted({k[0] for k in best})
    lines = ["# Leaderboard", "",
             "Generated by `python -m benchev.cli report` from `results/registry.jsonl`; do not edit. "
             "Markers: ᵖ paper-reported, ⁱ imported (unverified), ⁱ✓ imported (parity-verified), none = BenchEval harness. "
             "Cells are `1-step ‖ 2-step`; MedSPOT cells are TCA `strict / ±14 px`. Accuracy in %.", "",
             "## Summary", "", "| model | " + " | ".join(ORDER) + " |", "|---|" + "---|" * len(ORDER)]

    def cell(m, b, mode):
        if b == "medspot":
            s, t = best.get((m, b, mode, "rule=strict")), best.get((m, b, mode, "rule=tol14px"))
            if not s:
                return "–"
            return f"{_val(s)}{_mark(s)}" + (f" / {_val(t)}{_mark(t)}" if t else "")
        r = best.get((m, b, mode, "all"))
        return f"{_val(r)}{_mark(r)}" if r else "–"

    for m in models:
        lines.append(f"| {m} | " + " | ".join(f"{cell(m, b, '1step')} ‖ {cell(m, b, '2step')} " for b in ORDER) + "|")
    for b in ORDER:   # per-benchmark split tables
        splits = sorted({k[3] for k in best if k[1] == b and k[3] != "all"})
        bm = sorted({k[0] for k in best if k[1] == b})
        if not bm or b == "medspot":
            continue
        lines += ["", f"## {b} (1-step ‖ 2-step)", "", "| " + " | ".join(["model", "all"] + splits) + " |",
                  "|---|---|" + "---|" * len(splits)]
        for m in bm:
            def sc(split, mode, m=m, b=b):
                r = best.get((m, b, mode, split))
                return f"{_val(r)}{_mark(r)}" if r else "–"
            lines.append(f"| {m} | " + " | ".join(f"{sc(s, '1step')} ‖ {sc(s, '2step')}" for s in ["all"] + splits) + " |")
    lines += ["", "## Other protocols / partial", "",
              "| model | bench | split | mode | protocol | value | provenance | status | source |",
              "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(other, key=lambda r: (r.bench, r.model_id, r.mode, r.split)):
        lines.append(f"| {r.model_id} | {r.bench} | {r.split} | {r.mode} | {r.protocol_id} | {_val(r)} | "
                     f"{r.provenance} | {r.status} | {r.source} |")
    return "\n".join(lines) + "\n"


def write(registry_path, out_path):
    Path(out_path).write_text(build(load(registry_path)), encoding="utf-8")


# ---------------------------------------------------------------- MedSPOT comparison table
MEDSPOT_COLS = ("TCA (%)", "SHR (%)", "step1_accuracy (%)", "prefix_SHR (%)")


def _no_point_pct(r):
    """Share of the run's predictions without a point (unparsable / refused), from its predictions.jsonl."""
    import json
    p = Path(r.source) / "predictions.jsonl"
    if not p.exists():
        return None
    recs = [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()]
    return round(100 * sum(x.get("point") is None for x in recs) / len(recs), 1) if recs else None


def _flags(m):
    out = list(m.flags)
    p = m.parity
    if p:
        out.append(f"parity {'✓' if p['status'] == 'pass' else 'miss'} {p['bench']} {p['delta']:+.1f}")
    elif "no-published-reference" not in m.flags and m.kind != "ours":
        out.append("parity pending")
    if m.max_pixels:
        out.append(f"max_pixels={m.max_pixels}")
    return "; ".join(out)


def medspot_table(rows, models, no_point=_no_point_pct) -> str:
    """Strict medspot@v1 harness rows only, ours and comparison models in separate blocks, each sorted by TCA."""
    keep = [r for r in rows if r.bench == "medspot" and r.protocol_id == "medspot@v1" and r.split == "rule=strict"
            and r.provenance == "harness" and r.status == "complete" and r.model_id in models]
    head = ("| model | params | mode | TCA | SHR | step-1 acc | prefix SHR | no point % | notes |\n"
            "|---|---|---|---|---|---|---|---|---|")
    out = ["# MedSPOT comparison (strict medspot@v1, harness runs only)", "",
           "Generated by `benchev.cli report --medspot-table`; never hand-edit.", ""]
    for title, ours in (("## Our models", True), ("## Comparison models", False)):
        out += [title, "", head]
        for r in sorted((r for r in keep if (models[r.model_id].kind == "ours") == ours),
                        key=lambda r: -r.metrics["TCA (%)"]):
            m, np_ = models[r.model_id], no_point(r)
            vals = " | ".join(f"{r.metrics.get(c, '')}" for c in MEDSPOT_COLS)
            out.append(f"| {r.model_id} | {m.params or ''} | {r.mode} | {vals} | {'' if np_ is None else np_} | {_flags(m)} |")
        out.append("")
    return "\n".join(out)


def write_medspot_table(registry_path, out_path):
    from benchev.config import all_models
    models = {m.id: m for m in all_models()}
    Path(out_path).write_text(medspot_table(load(registry_path), models), encoding="utf-8")
